let x = 16.75;

let roundedValue = Math.round(x);
console.log("Rounded: " + roundedValue);

let sqrtValue = Math.sqrt(x);
console.log("Square root: " + sqrtValue);

let powerValue = Math.pow(x, 3);
console.log("Power of 3: " + powerValue);

let randomNum = Math.floor(Math.random() * 41) + 10;
console.log("Random number (10-50): " + randomNum);